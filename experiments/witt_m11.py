"""Re-derive the archived facts about the Witt design S(4,5,11) and write its Lean data.

Usage (from the repository root): python experiments/witt_m11.py [--lean]

Checks, from `data/instances/w11.json`: self-transversality, the Steiner property (every
4-set in exactly one block), the block-intersection sizes, `|Aut|`, that only the identity
fixes the points 0,1,2,3, and the two FK-A children's group orders. With `--lean`, writes
`lean/HypergraphDualization/WittData.lean`: the blocks and a Schreier transversal of `Aut`
along the base (0, 1, 2, 3), i.e. lists U1..U4 with every automorphism uniquely
u1*u2*u3*u4, u_k fixing 0..k-2 and the U_k images of point k-1 all distinct.
Deterministic; vertices 0-indexed.
"""
import sys
from collections import Counter
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fka.automorphism import hypergraph_automorphisms  # noqa: E402
from fka.hypergraph import Hypergraph, verts  # noqa: E402
from fka.instances import load  # noqa: E402
from fka.selfdual import is_primitive, is_transitive  # noqa: E402
from fka.transversal import minimal_elements, transversal  # noqa: E402

inst = load("w11")
H = inst.cnf
n = H.n
blocks = [frozenset(verts(e)) for e in H.edges]
print("points", n, "blocks", len(blocks), "sizes", Counter(len(b) for b in blocks))
print("self-transversal:", transversal(H).edges == H.edges)
four = Counter()
for b in blocks:
    for s in combinations(sorted(b), 4):
        four[s] += 1
print("4-sets covered", len(four), "of 330; multiplicities", Counter(four.values()))
print("pair intersections", Counter(len(a & b) for a, b in combinations(blocks, 2)))

aut = hypergraph_automorphisms(H, cap=10**6)
print("|Aut|", len(aut), "transitive", is_transitive(aut, n), "primitive", is_primitive(aut, n))
fix4 = [p for p in aut if all(p[i] == i for i in range(4))]
print("automorphisms fixing 0,1,2,3:", len(fix4))
tuples = {tuple(p[i] for i in range(4)) for p in aut}
print("images of (0,1,2,3):", len(tuples), "= 11*10*9*8 =", 11 * 10 * 9 * 8)


def child_order(G: Hypergraph) -> int:
    """|Aut| on the vertices G uses."""
    Gc, _ = G.compact()
    return len(hypergraph_automorphisms(Gc, cap=10**6))


x = 0
dele = Hypergraph(n, tuple(e for e in H.edges if not e >> x & 1))
con = Hypergraph(n, minimal_elements(e & ~(1 << x) for e in H.edges))
for name, G in (("deletion", dele), ("contraction", con)):
    Gc, _ = G.compact()
    g = hypergraph_automorphisms(Gc, cap=10**6)
    print(f"{name} child at v{x}: {len(G)} edges, sizes {Counter(len(verts(e)) for e in G.edges)},"
          f" |Aut| {len(g)}, transitive {is_transitive(g, Gc.n)}, primitive {is_primitive(g, Gc.n)}")

# Schreier transversal along the base 0,1,2,3.
U = []
level = aut
for k in range(4):
    reps = {}
    for p in sorted(level):
        reps.setdefault(p[k], p)
    U.append([reps[y] for y in sorted(reps)])
    level = [p for p in level if p[k] == k]
print("transversal sizes", [len(u) for u in U])

if "--lean" in sys.argv:
    def vec(p):
        return "#[" + ", ".join(str(i) for i in p) + "]"

    def inv(p):
        q = [0] * len(p)
        for i, j in enumerate(p):
            q[j] = i
        return q

    out = [
        "/-",
        "Generated by experiments/witt_m11.py --lean from data/instances/w11.json. Do not edit.",
        "",
        "`w11`: the 66 blocks of the Witt design `S(4,5,11)`, 0-indexed. `wittU k`: a Schreier",
        "transversal of `Aut(w11)` along the base `0, 1, 2, 3`; the `k`-th list fixes `0 .. k-1`",
        "and sends `k` to each possible image once.",
        "-/",
        "import HypergraphDualization.Algorithm",
        "",
        "namespace HD.Witt",
        "",
        "open HD",
        "",
        "/-- A permutation of `Fin 11` from its table and the table of its inverse. Arrays, not",
        "`![…]`, so that `native_decide` evaluates a point in O(1). -/",
        "def mk (f g : Array (Fin 11))",
        "    (h : ∀ x : Fin 11, g[(f[x.val]!).val]! = x ∧ f[(g[x.val]!).val]! = x := by decide) :",
        "    Equiv.Perm (Fin 11) :=",
        "  ⟨fun x => f[x.val]!, fun x => g[x.val]!, fun x => (h x).1, fun x => (h x).2⟩",
        "",
        "/-- The blocks of the Witt design `S(4,5,11)` as a list: `native_decide` iterates a list",
        "literal cheaply, while the `insert` chain of a `Finset` literal is rebuilt on each use. -/",
        "def w11L : List (Finset (Fin 11)) := [" + ", ".join(
            "{" + ", ".join(str(v) for v in sorted(b)) + "}" for b in sorted(sorted(b) for b in blocks)
        ) + "]",
        "",
        "/-- The Witt design `S(4,5,11)`. -/",
        "def w11 : HG 11 := w11L.toFinset",
        "",
    ]
    for k, u in enumerate(U):
        out.append(f"/-- Transversal level {k}: fixes `0 .. {k - 1}`, sends `{k}` everywhere it can go. -/")
        out.append(f"def wittU{k} : List (Equiv.Perm (Fin 11)) := [")
        out.append(",\n".join(f"  mk {vec(p)} {vec(inv(p))}" for p in u))
        out.append("]")
        out.append("")
    out.append("end HD.Witt")
    path = ROOT / "lean" / "HypergraphDualization" / "WittData.lean"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote", path)
