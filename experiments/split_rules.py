"""FK-A's subproblem count delta under three split rules (research §4, tracks 2 and 3).

Usage (from the repository root): python experiments/split_rules.py [--deep]
Writes results/split-rules.md. The rows for n > 32 use experiments/readonce_dag (build it with
cargo build --release); --deep adds GK f4 under the degree-sum rule (about five minutes).

Rules (fka.algorithm.choose_split_var; Lean splitVar, leftRule, guardRule):
  degree_sum  the vertex of largest deg_C + deg_D, least index on ties (FK-A);
  leftmost    the least live vertex (Hertel's order; Lean leftmost_delta: delta <= 2n + 2 on
              read-once formulas with leaves in order);
  guarded     the least vertex with |C| <= s deg_C or |D| <= s deg_D, s = floor(log2 N), else
              degree_sum (Lean guardRule_frequent: FK96 Lemma 2.3.2's frequency at every node).
Every count is delta of modified FK-A, fka.memo.fk_a_memo or the formula simulations.
"""
import subprocess
import sys
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "experiments"))
sys.setrecursionlimit(100000)

import readonce_sim as R

from fka.hypergraph import Hypergraph
from fka.instances import list_ids, load
from fka.memo import fk_a_memo
from fka.transversal import transversal

RULES = ("degree_sum", "leftmost", "guarded")
RUST = ROOT / "experiments" / "readonce_dag" / "target" / "release" / "readonce_dag"
FLAG = {"degree_sum": [], "leftmost": ["--leftmost"], "guarded": ["--guarded"]}


def memo(C, D):
    return [fk_a_memo(C, D, split_rule=r).nodes for r in RULES]


def sim(f):
    """(n, N, delta per rule) of a read-once formula, simulated on formulas."""
    return R.MASK[f].bit_count(), R.T[f] + R.TD[f], [R.run(f, r)[1] for r in RULES]


def rust(f, rules):
    """(n, N, delta per rule) from readonce_dag; None where a rule is skipped."""
    out, n, N = [], 0, 0
    for r in RULES:
        if r not in rules:
            out.append(None)
            continue
        exe = RUST.with_suffix(".exe") if RUST.with_suffix(".exe").exists() else RUST
        n, N, delta, _ = map(int, subprocess.run([str(exe), "--delta-only", *FLAG[r]],
                                                 input=R.sexpr(f), capture_output=True, text=True,
                                                 check=True).stdout.split())
        out.append(delta)
    return n, N, out


def alt(d, arity, op, base=0):
    """The alternating tree of the given arity and depth d, root `op`, leaves in order."""
    if d == 0:
        return R.var(base)
    m = arity ** (d - 1)
    other = "&" if op == "|" else "|"
    return R.mk(op, [alt(d - 1, arity, other, base + i * m) for i in range(arity)])


def g6(a, b, c, d, e, f):
    """ro12's gadget (a | b) & (c | (d & (e | f)))."""
    v = R.var
    return R.mk("&", [R.mk("|", [v(a), v(b)]), R.mk("|", [v(c), R.mk("&", [v(d), R.mk("|", [v(e), v(f)])])])])


def copies(op, k):
    """k disjoint copies of g6 under `op`, roles interleaved: role i of copy j is i*k + j."""
    return R.mk(op, [g6(*[i * k + j for i in range(6)]) for j in range(k)])


def row(name, n, N, d):
    cells = ["—" if x is None else f"{x:,}" for x in d]
    return f"| {name} | {n} | {N:,} | " + " | ".join(cells) + " |"


def main(deep):
    head = "| pair | `n` | `N` | degree-sum | leftmost | guarded |\n| --- | --- | --- | --- | --- | --- |"
    ok = all(R.check(f, n, r) for f, n in [(R.gk(k), 2 ** (2 * k - 1)) for k in (1, 2, 3)] +
             [(R.tk(k), 4 ** k) for k in (1, 2)] for r in RULES)
    gen = "Generated by `python experiments/split_rules.py`" + (" --deep" if deep else "")
    out = ["# Split rules: delta of modified FK-A", "",
           gen + ". Research §4 (Theorems 4.13, 4.16, Proposition 4.18).", "",
           (f"Formula simulation agrees with `fka.algorithm` and `fka.memo` under all three rules on "
           f"GK `f1–f3`, TK `S1–S2`: {ok}."), "", "## Read-once pairs, leaves in order", "", head]
    for name, f in [("GK f2", R.gk(2)), ("GK f3", R.gk(3)), ("TK S2", R.tk(2)),
                    ("alternating, fan-in 3, depth 3", alt(3, 3, "|"))]:
        out.append(row(name, *sim(f)))
    if RUST.with_suffix(".exe").exists() or RUST.exists():
        for name, f, rules in [("GK f4", R.gk(4), ("leftmost", "guarded") + (("degree_sum",) if deep else ())),
                               ("GK f5", R.gk(5), ("leftmost", "guarded")),
                               ("TK S3", R.tk(3), RULES), ("TK S4", R.tk(4), ("leftmost", "guarded")),
                               ("alternating, fan-in 3, depth 4", alt(4, 3, "|"), RULES)]:
            out.append(row(name, *rust(f, rules)))
    out += ["", "## Copies of ro12's gadget, roles interleaved", "",
            "`N` grows exponentially through one side, so `δ/N` stays bounded.", "", head]
    for op in ("|", "&"):
        for k in range(1, 6):
            out.append(row(f"{'OR' if op == '|' else 'AND'} of {k}", *sim(copies(op, k))))
    out += ["", "## Uniform matroids: circuits of `U(k, n)` against bases of the dual", "",
            ("All degrees tie, so every rule splits on the least live vertex; the live vertices form a "
            "suffix and a subproblem is fixed by its type `U(k', n')`: `δ` is quadratic in `n`."), "", head]
    for n in (6, 8, 10, 12):
        for k in (1, n // 2 - 1, n // 2):
            C = Hypergraph.from_sets(n, [set(c) for c in combinations(range(n), k + 1)])
            D = transversal(C)
            out.append(row(f"U({k},{n})", n, len(C) + len(D), memo(C, D)))
    out += ["", "## The instance library", "", head]
    for i in list_ids():
        inst = load(i)
        out.append(row(i, inst.cnf.n, len(inst.cnf) + len(inst.dnf), memo(inst.cnf, inst.dnf)))
    C = Hypergraph.from_sets(12, [{0, 2, 8}, {0, 4}, {0, 8, 9}, {1, 3, 11}, {1, 5}, {1, 10, 11},
                                  {2, 6, 8}, {3, 7, 11}, {4, 6}, {5, 7}, {6, 8, 9}, {7, 10, 11}])
    out.append(row("ro12", 12, 21, memo(C, transversal(C))))
    (ROOT / "results" / "split-rules.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote results/split-rules.md")


if __name__ == "__main__":
    main("--deep" in sys.argv)
