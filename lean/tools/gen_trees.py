"""Write lean/HypergraphDualization/TreeFacts.lean from the computed recursion trees.

Usage (from the repository root): python lean/tools/gen_trees.py

For each automorphism-tree figure of Chapter 5 with an instance, the expected value is read
from results/<instance>.fk-a.modified.json in the printed numbering: the split vertex and
|Aut(C)| on the vertices C uses (1 for an empty C). Lean recomputes both with its own
FK-A and automorphism definitions. Generated, never edited by hand.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "lean" / "HypergraphDualization" / "TreeFacts.lean"
FIGS = json.loads((ROOT / "thesis/2024/figures/autotrees.json").read_text(encoding="utf-8"))
LEAN = {"f2g2": "f2g2", "fano": "fano", "6a": "sixA", "6b": "sixB", "6c": "sixC", "6d": "sixD",
        "7ver": "sevenVer", "8ver": "eightVer"}


def printed_order(res, rl):
    nodes = {x["node_id"]: x for x in res["nodes"]}
    kids = {i: list(x["children"]) for i, x in nodes.items()}
    if rl:
        kids[res["root_id"]] = list(reversed(kids[res["root_id"]]))
    order, stack = [], [res["root_id"]]
    while stack:
        u = stack.pop()
        order.append(nodes[u])
        stack.extend(reversed(kids[u]))
    return order


lines = [
    "/-",
    "Generated by lean/tools/gen_trees.py from results/*.fk-a.modified.json. Do not edit.",
    "",
    "For each tree figure of Chapter 5: in the printed numbering, the split vertex",
    "(0-indexed) and the automorphism group order of each node, recomputed by Lean.",
    "-/",
    "import HypergraphDualization.Trees",
    "",
    "namespace HD.Data",
    "",
    "open HD",
    "",
]
for fig, spec in FIGS.items():
    if fig.startswith("_") or "instance" not in spec:
        continue
    res = json.loads((ROOT / f"results/{spec['instance']}.fk-a.modified.json").read_text())
    rl = spec["root_order"] == "RL"
    entries = []
    for x in printed_order(res, rl):
        split = "none" if x["split_var"] is None else f"some {x['split_var'] - 1}"
        order = (x["analysis"].get("aut_C") or {}).get("order") or 1
        entries.append(f"({split}, {order})")
    name = LEAN[spec["instance"]]
    lines.append(f"/-- Figure `{fig}`: {len(entries)} nodes, root order {spec['root_order']}. -/")
    lines.append(f"theorem {name}_tree :")
    lines.append(f"    treeData {'true' if rl else 'false'} {name}C {name}D =")
    body = ", ".join(entries)
    chunks, cur = [], "      ["
    for part in body.split(", ("):
        piece = part if cur.endswith("[") else "(" + part
        if len(cur) + len(piece) + 2 > 98:
            chunks.append(cur + ",")
            cur = "       " + piece
        else:
            cur = cur + ("" if cur.endswith("[") else ", ") + piece
    chunks.append(cur + "] := by")
    lines.extend(chunks)
    lines.append("  native_decide")
    lines.append("")
lines.append("end HD.Data")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT}")
