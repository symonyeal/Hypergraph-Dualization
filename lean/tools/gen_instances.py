"""Write lean/HypergraphDualization/Data.lean from the repository's instance JSON.

Usage (from the repository root): python lean/tools/gen_instances.py

Vertices are shifted to 0-indexed `Fin n`. The as-printed forms of 6-A and 8-Ver come
from `_archive/20260804-verbatim-nontransversal/`; everything else from `data/instances/`.
Generated, never edited by hand.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "lean" / "HypergraphDualization" / "Data.lean"

SOURCES = [
    ("k3", "data/instances/k3.json"),
    ("fano", "data/instances/fano.json"),
    ("f2g2", "data/instances/f2g2.json"),
    ("sixA", "data/instances/6a.json"),
    ("sixB", "data/instances/6b.json"),
    ("sixC", "data/instances/6c.json"),
    ("sixD", "data/instances/6d.json"),
    ("sevenVer", "data/instances/7ver.json"),
    ("eightVer", "data/instances/8ver.json"),
    ("sixAPrinted", "_archive/20260804-verbatim-nontransversal/6a-verbatim.json"),
    ("eightVerPrinted", "_archive/20260804-verbatim-nontransversal/8ver-verbatim.json"),
]


def family(edges):
    inner = ", ".join("{" + ", ".join(str(v - 1) for v in sorted(e)) + "}" for e in edges)
    return "{" + inner + "}"


lines = [
    "/-",
    "Generated by lean/tools/gen_instances.py from data/instances/*.json and the archived",
    "as-printed forms. Do not edit. Vertices are 0-indexed: thesis `v_i` is `i - 1`.",
    "-/",
    "import HypergraphDualization.Algorithm",
    "",
    "namespace HD.Data",
    "",
    "open HD",
    "",
]
for name, rel in SOURCES:
    d = json.loads((ROOT / rel).read_text(encoding="utf-8"))
    n = d["n_vertices"]
    lines.append(f"/-- {d.get('name', d['id'])} (`{d['id']}`, {d.get('provenance', '')}): `C`. -/")
    lines.append(f"def {name}C : HG {n} := {family(d['cnf'])}")
    lines.append(f"/-- {d.get('name', d['id'])}: `D`. -/")
    lines.append(f"def {name}D : HG {n} := {family(d['dnf'])}")
    lines.append("")
lines.append("end HD.Data")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", OUT)
